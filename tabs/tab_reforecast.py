# Helper: turn week number into start and end dates
# -----------------------------------------------------------------------------
def get_week_dates(week_number: int, year: int = 2025):
    """
    Calculate start and end dates for a given week number (Week 36 starts 31 Aug 2025).

    We use Sunday–Saturday weeks so it lines up cleanly with the data in all_stores.
    """
    offset = week_number - FIRST_WEEK_NUMBER
    start_date = FIRST_WEEK_START + timedelta(weeks=offset)
    end_date = start_date + timedelta(days=6)
    return start_date, end_date


