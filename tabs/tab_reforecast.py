# Calendar & scenario settings
# -----------------------------------------------------------------------------
# Story:
# - Use history up to 31 Aug 2025 to build the initial "baseline" forecast.
# - Forecast from 1 Sep 2025 all the way to 31 Dec 2025.
# - Then each week we add new actuals and re-run the forecast over the SAME horizon.
HISTORY_END_FOR_INITIAL = datetime(2025, 8, 31)            # last day of history for baseline
INITIAL_FORECAST_START = datetime(2025, 9, 1)              # forecast start: 1 Sep 2025
FINAL_FORECAST_DATE = datetime(2025, 12, 31)               # forecast end for all runs

# Weeks for the “weekly reforecast” controls (based on your data cut)
FIRST_WEEK_NUMBER = 36                                     # week of 31 Aug–6 Sep
FIRST_WEEK_START = datetime(2025, 8, 31)                   # Sunday starting week 36
MAX_ACTUAL_WEEK = 43                                       # Week 43 ends 25 Oct 2025


def cleanup_store_forecast_files(store_name: str):
    """
    Delete the baseline/re-forecast JSON files generated by this tab for a store.

    We keep the canonical engine file (e.g. 'Parramatta.json') and only remove:
      - '<Store>_O.json'   -> baseline for this lab
      - '<Store>_W*.json'  -> weekly re-forecasts for this lab
    """
    folder = Path(FORECAST_DATA_FOLDER)
    base_name = FORECAST_DATA_FILE_NAMES[store_name].replace(".json", "")

    patterns = [
        f"{base_name}_O.json",   # baseline for this tab
        f"{base_name}_W*.json",  # weekly re-forecast files
    ]

    for pattern in patterns:
        for path in folder.glob(pattern):
            try:
                path.unlink()
                print(f"[Re-Forecast Lab] Deleted old file: {path}")
            except Exception as e:
                print(f"[Re-Forecast Lab] Could not delete {path}: {e}")


