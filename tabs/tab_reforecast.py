def save_forecast_output(store_name: str, output_data: dict, postfix: str = "") -> Path:
    """
    Save a forecast run to JSON so we can reload and compare later.
    postfix:
        "O"       -> Initial baseline
        "W36"     -> Week 36 re-forecast, etc.
    """
    file_name = FORECAST_DATA_FILE_NAMES[store_name]
    if postfix:
        file_name = file_name.replace(".json", f"_{postfix}.json")
    output_path = Path(FORECAST_DATA_FOLDER, file_name)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w") as f:
        json.dump(output_data, f, indent=4, default=str)

    return output_path


def load_forecast_output(store_name: str, postfix: str = ""):
    """
    Load a previous forecast run for the given store and postfix.
    """
    file_name = FORECAST_DATA_FILE_NAMES[store_name]
    if postfix:
        file_name = file_name.replace(".json", f"_{postfix}.json")
    output_path = Path(FORECAST_DATA_FOLDER, file_name)
    if output_path.exists():
        with open(output_path, "r") as f:
            return json.load(f)
    return None


