STORE_MAP_INPUTS = {
    "Castle Towers": "Mecca Castle Towers",
    "Double Bay": "Mecca Double Bay",
    "Parramatta": "Mecca Parramatta",
}

FORECAST_DATA_FOLDER = "data/forecast/"
