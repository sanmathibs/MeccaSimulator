def generate_weekly_template(week_number: int) -> pd.DataFrame:
    """
    Generate a simple 7-day template for a given week.
    Handy if you later decide to allow manual CSV uploads of actuals.
    """
    start_date, end_date = get_week_dates(week_number)
    dates = pd.date_range(start=start_date, end=end_date, freq="D")

    template_df = pd.DataFrame(
        {
            "Date": dates,
            "SalesActual": [45000, 38000, 39000, 41000, 43000, 52000, 48000],
            "HoursActual": [120, 105, 108, 112, 118, 135, 128],
        }
    )
    return template_df


def validate_weekly_data(df: pd.DataFrame, expected_week: int, year: int = 2025):
    """
    Basic validation if you ever wire up manual CSV uploads for weekly actuals.

    Returns:
        (is_valid: bool, message: str, week_start: datetime, week_end: datetime)
    """
    required_columns = ["Date", "SalesActual", "HoursActual"]

    missing_cols = [col for col in required_columns if col not in df.columns]
    if missing_cols:
        return False, f"Missing required columns: {', '.join(missing_cols)}", None, None

    try:
        df["Date"] = pd.to_datetime(df["Date"])
    except Exception as e:
        return False, f"Invalid date format: {str(e)}", None, None

    expected_start, expected_end = get_week_dates(expected_week, year)
    data_start = df["Date"].min()
    data_end = df["Date"].max()

    if data_start.date() != expected_start.date():
        return (
            False,
            f"Data start date {data_start.date()} doesn't match expected week "
            f"{expected_week} start {expected_start.date()}",
            None,
            None,
        )

    if data_end.date() != expected_end.date():
        return (
            False,
            f"Data end date {data_end.date()} doesn't match expected week "
            f"{expected_week} end {expected_end.date()}",
            None,
            None,
        )

    if len(df) != 7:
        return False, f"Expected 7 days of data, got {len(df)}", None, None

    null_counts = df[required_columns].isnull().sum()
    if null_counts.any():
        null_cols = null_counts[null_counts > 0]
        return False, f"Found null values in: {dict(null_cols)}", None, None

    return True, "Valid", expected_start, expected_end


def merge_weekly_data(existing_df: pd.DataFrame, new_weekly_df: pd.DataFrame) -> pd.DataFrame:
    """
    Merge new weekly data with existing historical data (avoid overlapping dates).
    """
    existing_df["Date"] = pd.to_datetime(existing_df["Date"])
    new_weekly_df["Date"] = pd.to_datetime(new_weekly_df["Date"])

    existing_df = existing_df[~existing_df["Date"].isin(new_weekly_df["Date"])]
    combined_df = pd.concat([existing_df, new_weekly_df], ignore_index=True)
    combined_df = combined_df.sort_values("Date").reset_index(drop=True)
    return combined_df


