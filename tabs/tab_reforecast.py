@st.cache_data(show_spinner=True)
def get_store_data(store_name: str, until_date: datetime | None = HISTORY_END_FOR_INITIAL):
    """
    Load historical sales & labour for a given store from all_stores.xlsx.

    Args:
        store_name: "Parramatta", "Castle Towers", "Double Bay"
        until_date: if provided, cut off data at this date (inclusive).
                    if None, return the full history for that store.
    """
    df_input = pd.read_excel("data/all_stores.xlsx")
    df_input["Date"] = pd.to_datetime(df_input["Date"])
    store_column_value = STORE_MAP_INPUTS[store_name]

    mask = df_input["Store"] == store_column_value
    if until_date is not None:
        mask &= df_input["Date"] <= until_date

    df_store = df_input.loc[mask, FORECAST_INPUT_REQUIRED_COLUMNS].copy()
    df_store.reset_index(drop=True, inplace=True)
    return df_store


def validate_input_data(df_store: pd.DataFrame) -> pd.DataFrame:
    """
    Ensure there are no missing dates in the input history.

    If a date is missing, we insert it with zeros for sales and hours so the
    forecasting engine sees a continuous timeline.
    """
    df_store["Date"] = pd.to_datetime(df_store["Date"])
    min_date = df_store["Date"].min()
    max_date = df_store["Date"].max()
    all_dates = pd.date_range(start=min_date, end=max_date)
    missing_dates = all_dates.difference(df_store["Date"])

    if not missing_dates.empty:
        missing_df = pd.DataFrame(
            [
                {
                    "Date": d,
                    "SalesActual": 0,
                    "SalesForecast": 0,
                    "HoursActual": 0,
                    "HoursForecast": 0,
                }
                for d in missing_dates
            ]
        )
        df_store = pd.concat([df_store, missing_df], ignore_index=True)
        df_store = df_store.sort_values("Date").reset_index(drop=True)

    print(
        f"Validated input data: {len(df_store)} records from "
        f"{min_date.date()} to {max_date.date()}"
    )
    return df_store


@st.cache_data(show_spinner=False)
def get_legacy_forecast_sigma(store_name: str):
    """
    Estimate the "noise" of the current legacy forecast.

    We take the historical error:
        legacy_error = SalesForecast - SalesActual
    and compute its standard deviation (σ).
    """
    df_hist = get_store_data(store_name, until_date=None)
    if df_hist is None or df_hist.empty:
        return None

    df_hist = validate_input_data(df_hist)
    errors = df_hist["SalesForecast"] - df_hist["SalesActual"]
    errors = errors.replace([np.inf, -np.inf], np.nan).dropna()

    if len(errors) == 0:
        return None

    return float(errors.std())


